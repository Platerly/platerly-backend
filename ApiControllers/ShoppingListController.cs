using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Platerly.Api.DTOs;
using Platerly.Api.Exceptions;
using Platerly.Api.Extensions;
using Platerly.Api.Services.Shopping;

namespace Platerly.Api.ApiControllers
{
    /// <summary>
    /// B2C controller for managing shopping lists: list CRUD, recipe ingredient
    /// aggregation, manual item management, bulk check operations, and shareable list links.
    /// Most endpoints require a valid JWT (<c>[Authorize]</c> per action); the shared-list
    /// read endpoint is anonymous.
    /// Premium limits enforced by the service layer return <c>402 Payment Required</c>.
    /// Base route: <c>api/shopping-list</c>.
    /// </summary>
    [ApiController]
    [Route("api/shopping-list")]
    public class ShoppingListController : ControllerBase
    {
        private readonly IShoppingListService _shoppingListService;
        private readonly ILogger<ShoppingListController> _logger;

        public ShoppingListController(
            IShoppingListService shoppingListService,
            ILogger<ShoppingListController> logger)
        {
            _shoppingListService = shoppingListService;
            _logger = logger;
        }

        private Guid? CurrentUserId() => User.GetUserIdOrNull();

        // ========== List CRUD ==========

        /// <summary>
        /// Retrieve all shopping lists owned by the authenticated user.
        /// </summary>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>200 OK</c> — array of shopping list summary DTOs.<br/>
        /// <c>401</c> — unauthenticated.
        /// </returns>
        [Authorize]
        [HttpGet]
        public async Task<IActionResult> GetMyLists(CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var lists = await _shoppingListService.GetUserListsAsync(userId.Value, ct);
            return Ok(lists);
        }

        /// <summary>
        /// Retrieve a specific shopping list with all its items, including recipe-sourced and
        /// manually added items. Only the owning user can access their list.
        /// </summary>
        /// <param name="listId">The shopping list GUID.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>200 OK</c> — full shopping list DTO.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — list not found.
        /// </returns>
        [Authorize]
        [HttpGet("{listId:guid}")]
        public async Task<IActionResult> GetList(Guid listId, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var list = await _shoppingListService.GetListAsync(listId, userId.Value, ct);
            if (list == null) return NotFound("Shopping list not found.");

            return Ok(list);
        }

        /// <summary>
        /// Retrieve a shopping list using a shareable token (public, no auth required).
        /// The token is generated by the owner via the <c>POST /{listId}/share</c> endpoint.
        /// Returns 404 when the list does not exist, the token is invalid, or sharing is disabled.
        /// </summary>
        /// <param name="shareToken">The opaque share token string.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>200 OK</c> — full shopping list DTO (read-only view).<br/>
        /// <c>400</c> — share token missing.<br/>
        /// <c>404</c> — list not found or sharing disabled.
        /// </returns>
        [AllowAnonymous]
        [HttpGet("shared/{shareToken}")]
        public async Task<IActionResult> GetSharedList(string shareToken, CancellationToken ct)
        {
            if (string.IsNullOrWhiteSpace(shareToken))
                return BadRequest("Share token is required.");

            var list = await _shoppingListService.GetListByShareTokenAsync(shareToken, ct);
            if (list == null) return NotFound("Shared list not found or sharing is disabled.");

            return Ok(list);
        }

        /// <summary>
        /// Create a new empty shopping list for the authenticated user.
        /// Free-tier users may be limited in the number of concurrent lists.
        /// </summary>
        /// <param name="dto">List metadata: name, optional description.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>201 Created</c> — the created shopping list DTO; Location header set.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>402</c> — free-tier list limit reached.
        /// </returns>
        [Authorize]
        [HttpPost]
        public async Task<IActionResult> CreateList([FromBody] CreateShoppingListDto dto, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            try
            {
                var list = await _shoppingListService.CreateListAsync(userId.Value, dto, ct);
                return CreatedAtAction(nameof(GetList), new { listId = list.Id }, list);
            }
            catch (PremiumRequiredException ex)
            {
                return StatusCode(402, new { error = "premium_required", code = ex.LimitCode, message = ex.Message });
            }
        }

        /// <summary>
        /// Update a shopping list's name or description.
        /// </summary>
        /// <param name="listId">The shopping list GUID to update.</param>
        /// <param name="dto">Updated fields (patch semantics).</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>200 OK</c> — updated shopping list DTO.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — list not found.
        /// </returns>
        [Authorize]
        [HttpPut("{listId:guid}")]
        public async Task<IActionResult> UpdateList(Guid listId, [FromBody] UpdateShoppingListDto dto, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var list = await _shoppingListService.UpdateListAsync(listId, userId.Value, dto, ct);
            if (list == null) return NotFound("Shopping list not found.");

            return Ok(list);
        }

        /// <summary>
        /// Soft-delete a shopping list and all its items.
        /// </summary>
        /// <param name="listId">The shopping list GUID to delete.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>204 No Content</c> on success.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — list not found.
        /// </returns>
        [Authorize]
        [HttpDelete("{listId:guid}")]
        public async Task<IActionResult> DeleteList(Guid listId, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var deleted = await _shoppingListService.DeleteListAsync(listId, userId.Value, ct);
            if (!deleted) return NotFound("Shopping list not found.");

            return NoContent();
        }

        // ========== Recipe Management ==========

        /// <summary>
        /// Add all ingredients from a recipe to the shopping list, optionally scaled.
        /// If the same recipe has already been added, a <c>409 Conflict</c> is returned.
        /// Premium limits may apply for recipes-per-list counts.
        /// </summary>
        /// <param name="listId">The target shopping list GUID.</param>
        /// <param name="dto">Contains <c>RecipeId</c> and optional <c>ScaleFactor</c> (default 1.0).</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>200 OK</c> — updated shopping list DTO.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>402</c> — premium limit reached.<br/>
        /// <c>404</c> — list not found.<br/>
        /// <c>409</c> — recipe already added to this list.
        /// </returns>
        [Authorize]
        [HttpPost("{listId:guid}/recipes")]
        public async Task<IActionResult> AddRecipe(Guid listId, [FromBody] AddRecipeToListDto dto, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            try
            {
                _logger.LogInformation("Adding recipe {RecipeId} to list {ListId} for user {UserId}", dto.RecipeId, listId, userId);

                var list = await _shoppingListService.AddRecipeToListAsync(listId, userId.Value, dto, ct);
                if (list == null) return NotFound("Shopping list not found.");

                return Ok(list);
            }
            catch (DuplicateRecipeException ex)
            {
                return Conflict(new { error = "duplicate_recipe", message = ex.Message });
            }
            catch (PremiumRequiredException ex)
            {
                return StatusCode(402, new { error = "premium_required", code = ex.LimitCode, message = ex.Message });
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error adding recipe {RecipeId} to list {ListId}", dto.RecipeId, listId);
                return StatusCode(500, new { error = "server_error", message = "Failed to add recipe to shopping list" });
            }
        }

        /// <summary>
        /// Remove a previously added recipe and all its ingredient items from the shopping list.
        /// Items added from other recipes or manually are not affected.
        /// </summary>
        /// <param name="listId">The shopping list GUID.</param>
        /// <param name="recipeId">The recipe GUID to remove.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>204 No Content</c> on success.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — list not found.
        /// </returns>
        [Authorize]
        [HttpDelete("{listId:guid}/recipes/{recipeId:guid}")]
        public async Task<IActionResult> RemoveRecipe(Guid listId, Guid recipeId, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var removed = await _shoppingListService.RemoveRecipeFromListAsync(listId, userId.Value, recipeId, ct);
            if (!removed) return NotFound("Shopping list not found.");

            return NoContent();
        }

        /// <summary>
        /// Convenience endpoint: creates a new shopping list pre-populated with all ingredients
        /// from the specified recipe, optionally scaled. The list is named after the recipe title.
        /// </summary>
        /// <param name="recipeId">The source recipe GUID.</param>
        /// <param name="scaleFactor">Ingredient quantity multiplier (default 1.0).</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>201 Created</c> — the new shopping list DTO.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>402</c> — premium limit reached.
        /// </returns>
        [Authorize]
        [HttpPost("from-recipe/{recipeId:guid}")]
        public async Task<IActionResult> CreateFromRecipe(Guid recipeId, [FromQuery] decimal scaleFactor = 1.0m, CancellationToken ct = default)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            try
            {
                _logger.LogInformation("Creating shopping list from recipe {RecipeId} for user {UserId}", recipeId, userId);

                var list = await _shoppingListService.CreateFromRecipeAsync(userId.Value, recipeId, scaleFactor, ct);
                return CreatedAtAction(nameof(GetList), new { listId = list.Id }, list);
            }
            catch (PremiumRequiredException ex)
            {
                return StatusCode(402, new { error = "premium_required", code = ex.LimitCode, message = ex.Message });
            }
            catch (Exception ex)
            {
                _logger.LogError(ex, "Error creating shopping list from recipe {RecipeId}", recipeId);
                return StatusCode(500, new { error = "server_error", message = "Failed to create shopping list from recipe" });
            }
        }

        // ========== Item Management ==========

        /// <summary>
        /// Add a manually entered item (not sourced from a recipe) to the shopping list.
        /// </summary>
        /// <param name="listId">The target shopping list GUID.</param>
        /// <param name="dto">Item details: name, optional quantity and unit.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>200 OK</c> — the created item DTO.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — list not found.
        /// </returns>
        [Authorize]
        [HttpPost("{listId:guid}/items")]
        public async Task<IActionResult> AddItem(Guid listId, [FromBody] AddManualItemDto dto, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var item = await _shoppingListService.AddManualItemAsync(listId, userId.Value, dto, ct);
            if (item == null) return NotFound("Shopping list not found.");

            return Ok(item);
        }

        /// <summary>
        /// Partially update a shopping list item: check/uncheck it, change its quantity,
        /// or add/update a note. Uses PATCH semantics — only provided fields are changed.
        /// </summary>
        /// <param name="listId">The parent shopping list GUID.</param>
        /// <param name="itemId">The item GUID to update.</param>
        /// <param name="dto">Fields to patch (isChecked, quantity, note).</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>200 OK</c> — updated item DTO.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — item not found.
        /// </returns>
        [Authorize]
        [HttpPatch("{listId:guid}/items/{itemId:guid}")]
        public async Task<IActionResult> UpdateItem(Guid listId, Guid itemId, [FromBody] UpdateItemDto dto, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var item = await _shoppingListService.UpdateItemAsync(listId, itemId, userId.Value, dto, ct);
            if (item == null) return NotFound("Item not found.");

            return Ok(item);
        }

        /// <summary>
        /// Remove a single item from the shopping list.
        /// </summary>
        /// <param name="listId">The parent shopping list GUID.</param>
        /// <param name="itemId">The item GUID to remove.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>204 No Content</c> on success.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — item not found.
        /// </returns>
        [Authorize]
        [HttpDelete("{listId:guid}/items/{itemId:guid}")]
        public async Task<IActionResult> DeleteItem(Guid listId, Guid itemId, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var deleted = await _shoppingListService.DeleteItemAsync(listId, itemId, userId.Value, ct);
            if (!deleted) return NotFound("Item not found.");

            return NoContent();
        }

        /// <summary>
        /// Check or uncheck multiple items in a single request.
        /// Useful for "check all" / "uncheck all" UI actions.
        /// </summary>
        /// <param name="listId">The shopping list GUID.</param>
        /// <param name="dto">Contains <c>ItemIds</c> (array of GUIDs) and <c>IsChecked</c> flag.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>200 OK</c> — <c>{ updatedCount: int }</c>.<br/>
        /// <c>401</c> — unauthenticated.
        /// </returns>
        [Authorize]
        [HttpPost("{listId:guid}/items/bulk-check")]
        public async Task<IActionResult> BulkCheckItems(Guid listId, [FromBody] BulkCheckItemsDto dto, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var count = await _shoppingListService.BulkCheckItemsAsync(listId, userId.Value, dto, ct);
            return Ok(new { updatedCount = count });
        }

        /// <summary>
        /// Remove all checked (completed) items from the list while leaving unchecked items intact.
        /// </summary>
        /// <param name="listId">The shopping list GUID.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>204 No Content</c> on success.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — list not found.
        /// </returns>
        [Authorize]
        [HttpPost("{listId:guid}/items/clear-checked")]
        public async Task<IActionResult> ClearCheckedItems(Guid listId, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var cleared = await _shoppingListService.ClearCheckedItemsAsync(listId, userId.Value, ct);
            if (!cleared) return NotFound("Shopping list not found.");

            return NoContent();
        }

        /// <summary>
        /// Remove all items (checked and unchecked) from the list, leaving the list itself intact.
        /// </summary>
        /// <param name="listId">The shopping list GUID.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>204 No Content</c> on success.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — list not found.
        /// </returns>
        [Authorize]
        [HttpPost("{listId:guid}/items/clear-all")]
        public async Task<IActionResult> ClearAllItems(Guid listId, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var cleared = await _shoppingListService.ClearAllItemsAsync(listId, userId.Value, ct);
            if (!cleared) return NotFound("Shopping list not found.");

            return NoContent();
        }

        /// <summary>
        /// Remove all recipe-sourced items from the list while preserving manually added items.
        /// Also removes the recipe references from the list so the recipes can be re-added later.
        /// </summary>
        /// <param name="listId">The shopping list GUID.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>204 No Content</c> on success.<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — list not found.
        /// </returns>
        [Authorize]
        [HttpPost("{listId:guid}/recipes/clear-all")]
        public async Task<IActionResult> ClearAllRecipes(Guid listId, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var cleared = await _shoppingListService.ClearAllRecipesAsync(listId, userId.Value, ct);
            if (!cleared) return NotFound("Shopping list not found.");

            return NoContent();
        }

        // ========== Sharing ==========

        /// <summary>
        /// Enable or disable public sharing for a shopping list.
        /// When enabled, the service generates (or returns the existing) share token,
        /// which can be given to anyone to access the list anonymously via
        /// <c>GET api/shopping-list/shared/{shareToken}</c>.
        /// When disabled, the existing token is invalidated.
        /// </summary>
        /// <param name="listId">The shopping list GUID.</param>
        /// <param name="dto">Contains <c>IsShared: bool</c>.</param>
        /// <param name="ct">Cancellation token.</param>
        /// <returns>
        /// <c>200 OK</c> — <c>{ shareUrl: string? }</c> (null when sharing is disabled).<br/>
        /// <c>401</c> — unauthenticated.<br/>
        /// <c>404</c> — list not found (when enabling sharing).
        /// </returns>
        [Authorize]
        [HttpPost("{listId:guid}/share")]
        public async Task<IActionResult> SetSharing(Guid listId, [FromBody] ShareListDto dto, CancellationToken ct)
        {
            var userId = CurrentUserId();
            if (userId == null) return Unauthorized();

            var result = await _shoppingListService.SetSharingAsync(listId, userId.Value, dto, ct);
            if (result.ShareUrl == null && dto.IsShared)
                return NotFound("Shopping list not found.");

            return Ok(result);
        }
    }
}
