    /// <summary>
    /// Seeds 50 manually verified halal recipes into RecipeIndex.
    /// Every recipe in this seed has been individually reviewed for halal compliance.
    /// This seed provides immediate search content while the automated indexer runs.
    ///
    /// Idempotent: checks for the curated source record before inserting.
    /// </summary>
    public class HalalRecipeSeed
    {
        private const string CuratedDomain = "recipzee.com";
        private const string CuratedSource = "Recipzee Curated Collection";

        private readonly PlaterlyDbContext _db;
        private readonly ILogger<HalalRecipeSeed> _logger;

        public HalalRecipeSeed(PlaterlyDbContext db, ILogger<HalalRecipeSeed> logger)
        {
            _db     = db;
            _logger = logger;
        }

        public async Task SeedAsync(CancellationToken ct = default)
        {
            // Check if already seeded
            var alreadySeeded = await _db.RecipeIndexSources
                .AnyAsync(s => s.SourceDomain == CuratedDomain, ct);

            if (alreadySeeded)
            {
                _logger.LogDebug("[HalalRecipeSeed] Already seeded — skipping.");
                return;
            }

            _logger.LogInformation("[HalalRecipeSeed] Seeding 50 curated halal recipes...");

            var source = new RecipeIndexSource
            {
                SourceName            = CuratedSource,
                SourceDomain          = CuratedDomain,
                ApiEndpoint           = "internal",
                LegalNotes            = "Manually curated halal recipes created and owned by Recipzee. " +
                                        "All recipes individually reviewed for halal compliance.",
                AllowsThumbnailDisplay = false,
                RequestDelayMs        = 0,
                IsActive              = true,
                RequiresApiKey        = false
            };

            _db.RecipeIndexSources.Add(source);
            await _db.SaveChangesAsync(ct);

            var recipes = GetSeedRecipes();
            int count   = 0;

            foreach (var r in recipes)
            {
                _db.RecipeIndex.Add(new RecipeIndexRecord
                {
                    Title            = r.Title,
                    SourceUrl        = $"https://recipzee.com/recipes/curated/{r.Slug}",
                    SourceDomain     = CuratedDomain,
                    OriginalAuthor   = "Recipzee",
                    IngredientsJson  = JsonSerializer.Serialize(r.Ingredients),
                    InstructionsJson = JsonSerializer.Serialize(r.Instructions),
                    IndexedAt        = DateTime.UtcNow,
                    CuisineType      = r.CuisineType,
                    ServingSize      = r.ServingSize,
                    PrepTimeMinutes  = r.PrepMins,
                    CookTimeMinutes  = r.CookMins,
                    TagsJson         = JsonSerializer.Serialize(r.Tags),
                    IsAnalysed       = false,
                    SourceId         = source.Id
                });

                count++;
                if (count % 10 == 0)
                    await _db.SaveChangesAsync(ct);
            }

            source.TotalRecipesIndexed = count;
            await _db.SaveChangesAsync(ct);

            _logger.LogInformation("[HalalRecipeSeed] Seeded {Count} recipes.", count);
        }

